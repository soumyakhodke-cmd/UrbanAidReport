import path from "node:path";
import { fileURLToPath } from "node:url";
import compression from "compression";
import cors from "cors";
import express from "express";
import rateLimit from "express-rate-limit";
import helmet from "helmet";
import { config } from "./config/env.js";
import { errorHandler, notFoundHandler } from "./middleware/errorHandler.js";
import authRouter from "./routes/auth.js";
import reportsRouter from "./routes/reports.js";
import walletRouter from "./routes/wallet.js";

const app = express();
const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
app.set("trust proxy", 1);
app.disable("x-powered-by");
app.use(helmet({ contentSecurityPolicy: false, crossOriginResourcePolicy: { policy: "cross-origin" } }));
app.use(compression());
app.use(cors({ origin(origin, callback) { if (!origin || !config.allowedOrigins.length || config.allowedOrigins.includes(origin)) return callback(null, true); return callback(new Error("Origin is not allowed.")); } }));
app.use(express.json({ limit: "200kb" }));
app.use("/api", rateLimit({ windowMs: 15 * 60 * 1000, limit: 250, standardHeaders: "draft-7", legacyHeaders: false }));
app.use("/api/auth", rateLimit({ windowMs: 15 * 60 * 1000, limit: 30, standardHeaders: "draft-7", legacyHeaders: false }));
app.get("/api/health", (req, res) => res.status(200).json({ status: "ok", mode: "local-demo" }));
app.use("/api/auth", authRouter);
app.use("/api/reports", reportsRouter);
app.use("/api/wallet", walletRouter);
app.get("/auth/callback", (req, res) => res.sendFile(path.join(rootDir, "public", "index.html")));
app.use(express.static(path.join(rootDir, "public"), { extensions: ["html"], maxAge: config.nodeEnv === "production" ? "1h" : 0 }));
app.use(notFoundHandler);
app.use(errorHandler);
export default app;
